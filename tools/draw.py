from __future__ import annotations

from tools.registry import Tool, ToolContext, TIER_CONTEXTUAL
from persona.gender import g as gpick, gender_of
from persona.prompt_context import ContextSpec


def _state_of(ctx: ToolContext) -> dict | None:
    mem = getattr(ctx, "memory", None)
    return getattr(mem, "_session_state_ref", None) if mem is not None else None


def _draw_handler(args: dict, ctx: ToolContext) -> str:
    _cg = gender_of(getattr(getattr(ctx, "persona", None), "character", None))
    intent = (args.get("intent") or "").strip()
    if not intent:
        ref = ((_state_of(ctx) or {}).get("last_shown_image_tags") or {})
        if ref.get("tags"):
            intent = ("в такой же позе и обстановке, как на картинке из "
                      "интернета, которую я недавно "
                      + gpick(_cg, "показала", "показал"))
    if not intent:
        return ("draw вызван БЕЗ intent — так снимок не сделать. intent "
                "обязателен: короткая фраза, ГДЕ ты и ЧТО делаешь. Выбери ОДНО: "
                "(1) хочешь снимок — вызови draw ОДИН раз и впиши в intent, "
                "где ты и что делаешь; (2) снимок не нужен или ты ещё не "
                + gpick(_cg, "решила", "решил")
                + " что показать — НЕ вызывай draw, просто ответь словами. "
                "Пустой draw снова вернёт эту же ошибку — не повторяй его.")

    if len(intent) < 5:
        return (f"intent слишком короткий ({len(intent)} символов) — кадр по "
                f"нему не собрать. Опиши конкретнее одной фразой: где ты, что "
                f"делаешь, какое настроение. Если снимок не нужен — просто "
                f"ответь словами, без "
                f"вызова draw.")

    for existing in ctx.pending_actions:
        if existing.get("kind") == "image":
            return ("Снимок УЖЕ делается по первому вызову — повторный draw "
                    "не нужен и проигнорирован.")

    ctx.pending_actions.append({
        "kind": "image",
        "intent": intent,
    })

    return ("Запрос принят: снимок будет сделан и придёт в чат отдельным "
            "сообщением через ~30-60 сек — тогда ты его увидишь и ответишь "
            "на него. Твоя реплика на этом завершена.")



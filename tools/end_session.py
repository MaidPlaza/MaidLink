from tools.registry import Tool, ToolContext, TIER_CONTEXTUAL


def _end_session_handler(args: dict, ctx: ToolContext) -> str:
    reason = (args.get("reason") or "разговор естественно завершён").strip()

    ctx.pending_actions.append({
        "kind": "end_session",
        "reason": reason,
    })

    return ("OK. Сессия закроется сама. Если прощание уже сказано — НЕ повторяй "
            "его и ничего не добавляй; если нет — попрощайся одной репликой. "
            "Про закрытие сессии не упоминай.")


END_SESSION_SCHEMA = {
    "name": "end_session",
    "description": "Закрыть сессию когда разговор окончен. Вызывай ПОСЛЕ прощальной реплики.",
    "parameters": {
        "type": "object",
        "properties": {
            "reason": {"type": "string", "description": "короткая причина для лога (опц)"},
        },
    },
}


END_SESSION_HELP = """end_session(reason?) — закрыть текущую сессию.

Когда вызывать:
  - Пользователь попрощался («пока», «спокойной ночи», «увидимся», «до завтра»)
  - Пользователь поблагодарил и закругляется («ок, всё, спасибо», «понял, всё ясно»)
  - Тема исчерпана, нет открытых вопросов, и пользователь явно завершает разговор

Когда НЕ вызывать:
  - Пользователь явно ждёт ответа на свой вопрос — даже короткое «ок»
    может быть началом нового thread-а
  - Есть открытые задачи или незавершённые темы
  - Ты сомневаешься — лучше не закрывать; idle-таймер закроет автоматически
    через 15 минут если разговор реально окончен

Порядок действий внутри одного твоего turn-а:
  1. Сначала отвечай нормальным прощанием в твоём стиле
  2. ПОСЛЕ этого вызови end_session
  3. Больше ничего не пиши — прощание уже сказано, повторять его нельзя

Пример:
  Господин: «Спасибо, всё! Пока!»
  Ты:      «Хорошего дня, Господин! До завтра~»
           — и в этом же ходе вызываешь end_session
           с reason="Господин попрощался коротко"
"""


END_SESSION_TOOL = Tool(
    name="end_session",
    schema=END_SESSION_SCHEMA,
    handler=_end_session_handler,
    summary=(
        "end_session(reason?) — закрыть сессию когда разговор окончен. "
        "Вызывай ПОСЛЕ прощальной реплики, не до."
    ),
    help=END_SESSION_HELP,
    tier=TIER_CONTEXTUAL,
    capability="session_lifecycle",
    triggers=[
        "пока", "увидимся", "до завтра", "до скорого",
        "до свидания", "до встречи", "до утра",
        "спокойной ночи", "доброй ночи",
        "всё, спасибо", "ок, всё", "на этом всё", "хватит",
        "прощай", "бай", "гудбай",
        "спасибо за всё", "до связи",
    ],
)
